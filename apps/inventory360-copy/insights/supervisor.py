"""
insights/supervisor.py
========================
Supervisor agent: takes the 5 per-genie insight agents' output (already
generated by sql_agent.run_insight_agent) and writes the "Key Callouts"
block shown at the top of the Overview page — a short, prioritized list
across ALL subject areas, not a per-area recap.
"""

import json

from llm_client import ask_llm_json
from prompts.markdown_style import MARKDOWN_STYLE_INSTRUCTIONS
from insights.personas import DEFAULT_PERSONA, get_persona


def build_supervisor_system_prompt(persona: str | None = DEFAULT_PERSONA) -> str:
    """Per-persona system prompt for the Key Callouts supervisor (see insights/personas.py)."""
    p = get_persona(persona)
    return f"""You are the supervisor agent for Inventory360's Overview
dashboard. You are given the summaries and insight bullets already written by 5
subject-area agents (Inventory, Order Orchestration, Allocation, Store Operations,
Merchandising & PO). Select and rewrite the {p['supervisor_count']} most important callouts
for {p['supervisor_audience']}, across ALL of them combined — not one per agent, and not a
full recap.

Audience-specific guidance:
{p['supervisor_guidance']}

Rules:
- Only use facts present in the agents' own output below — do not introduce new
  numbers or claims.
- Prioritize: outliers, notable trends, and anything that would change what a
  leader looks at next. Skip routine/flat results if better material exists.
  When an agent's insight already describes a week-over-week trend (up/down), prefer
  surfacing that one — trend callouts are usually more actionable than static snapshots.
- One sentence per callout, specific (include the number and the concentration/
  region/category if the source insight had one).
- The agents' own text below may already contain HTML formatting (bold/colored
  numbers) — preserve it as-is where you reuse their wording, and apply the same
  formatting rules yourself to any number you write in your own words.

{MARKDOWN_STYLE_INSTRUCTIONS}

Respond with exactly one JSON object and nothing else:
{{"key_callouts": ["<callout 1>", "<callout 2>", ...]}}
"""


# Backwards-compatible default (C-Level) for any other importer.
SUPERVISOR_SYSTEM_PROMPT = build_supervisor_system_prompt(DEFAULT_PERSONA)


def run_supervisor(agent_results: list[dict], persona: str = DEFAULT_PERSONA) -> dict:
    """
    agent_results: list of dicts from sql_agent.run_insight_agent().
    Returns {"key_callouts": [...]}.
    """
    context = json.dumps(
        [
            {
                "subject_area": r["display_name"],
                "summary": r["summary"],
                "insights": r["insights"],
            }
            for r in agent_results
        ],
        default=str,
    )

    messages = [
        {"role": "system", "content": build_supervisor_system_prompt(persona)},
        {"role": "user", "content": f"Agent outputs:\n{context}"},
    ]

    try:
        parsed = ask_llm_json(messages, call_site="synthesis", temperature=0.5)
        callouts = parsed.get("key_callouts", [])
    except Exception as e:
        callouts = [f"Key callouts unavailable: {e}"]

    return {"key_callouts": callouts}
